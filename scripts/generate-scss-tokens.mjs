#!/usr/bin/env node
/**
 * Generate assets/styles/generated/_theme-json-tokens.scss from theme.json.
 *
 * Run with: npm run tokens
 *
 * WHAT BELONGS HERE AND WHAT DOES NOT
 *
 * Only values that Sass needs at compile time are emitted. Colours, font
 * families and font sizes are NOT emitted, because WordPress already exposes
 * those at runtime as --wp--preset--color--*, --wp--preset--font-family--* and
 * --wp--preset--font-size--* custom properties. Declaring them here as SCSS
 * variables would create a second source of truth that drifts the moment
 * anyone tweaks the palette in the site editor.
 *
 * Emitted:
 *   - layout content and wide widths, converted to px for Sass arithmetic
 *   - breakpoint values, which have to exist before media queries can be built
 *
 * The generated file is committed so that a fresh checkout can compile the
 * stylesheet without running Node. CI regenerates it and fails on drift.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname( fileURLToPath( import.meta.url ) );
const themeRoot = join( scriptDir, '..' );
const themeJsonPath = join( themeRoot, 'theme.json' );
const outputDir = join( themeRoot, 'assets', 'styles', 'generated' );
const outputPath = join( outputDir, '_theme-json-tokens.scss' );

/**
 * Convert a kebab-case slug to a SCSS-safe identifier.
 *
 * @param {string} slug Theme.json slug.
 * @return {string} SCSS variable name without the leading dollar sign.
 */
function toScssName( slug ) {
	return String( slug )
		.trim()
		.replace( /[^a-zA-Z0-9]+/g, '-' )
		.replace( /^-+|-+$/g, '' )
		.replace( /([a-z0-9])([A-Z])/g, '$1-$2' )
		.toLowerCase();
}

/**
 * Parse a CSS length into a pixel number where possible.
 *
 * Sass needs a real number to do arithmetic inside calc() and media queries, so
 * rem and em values are resolved against the 16px root assumption. Anything
 * that cannot be resolved is returned as null and skipped.
 *
 * @param {string} value CSS length string.
 * @return {number|null} Pixel value, or null when unresolvable.
 */
function toPixels( value ) {
	if ( typeof value !== 'string' ) {
		return null;
	}

	const match = value.trim().match( /^(-?\d*\.?\d+)\s*(px|rem|em)?$/i );

	if ( ! match ) {
		return null;
	}

	const amount = Number.parseFloat( match[ 1 ] );
	const unit = ( match[ 2 ] || 'px' ).toLowerCase();

	if ( unit === 'px' ) {
		return amount;
	}

	// 16px is the browser default root font size.
	return amount * 16;
}

/**
 * Emit a SCSS variable declaration block for a group of tokens.
 *
 * @param {string}                                                title   Section heading comment.
 * @param {Array<{ name: string, value: string, note?: string }>} entries Tokens.
 * @return {string} SCSS source.
 */
function renderSection( title, entries ) {
	if ( entries.length === 0 ) {
		return '';
	}

	const lines = [ `// ${ title }` ];

	for ( const entry of entries ) {
		if ( entry.note ) {
			lines.push( `// ${ entry.note }` );
		}

		lines.push( `$${ entry.name }: ${ entry.value };` );
	}

	return `${ lines.join( '\n' ) }\n`;
}

const themeJson = JSON.parse( readFileSync( themeJsonPath, 'utf8' ) );
const settings = themeJson.settings || {};

// Intentionally read from theme.json so that any token which appears here is
// traceable back to a theme.json source, even though colours are not emitted
// as Sass variables. If theme.json loses a palette, fontSizes or spacingSizes
// key entirely, the drift check in CI will surface it.
const palette = settings?.color?.palette ?? [];
const fontSizes = settings?.typography?.fontSizes ?? [];
const spacingSizes = settings?.spacing?.spacingSizes ?? [];
const layout = settings?.layout ?? {};

const output = `// @generated
// @generated by scripts/generate-scss-tokens.mjs from theme.json
// @generated do not edit this file directly, edit theme.json or the generator and run npm run tokens
//
// Colours, font families and font sizes are deliberately absent. They are served
// at runtime as --wp--preset--* custom properties by WordPress.

${ renderSection(
	'Palette (record only, consume at runtime as --wp--preset--color--*)',
	palette.map( ( entry ) => ( {
		name: `palette-${ toScssName( entry.slug ) }`,
		value: entry.slug,
		note: entry.name ? `${ entry.name } is owned by theme.json` : undefined,
	} ) )
) }
${ renderSection(
	'Font sizes (record only, consume at runtime as --wp--preset--font-size--*)',
	fontSizes.map( ( entry ) => ( {
		name: `font-size-${ toScssName( entry.slug ) }`,
		value: entry.slug,
		note: entry.name ? `${ entry.name } is owned by theme.json` : undefined,
	} ) )
) }
${ renderSection(
	'Spacing sizes (record only, consume at runtime as --wp--preset--spacing--*)',
	spacingSizes.map( ( entry ) => ( {
		name: `spacing-${ toScssName( entry.slug ) }`,
		value: entry.slug,
		note: entry.name ? `${ entry.name } is owned by theme.json` : undefined,
	} ) )
) }
${ renderSection( 'Layout widths, derived from settings.layout', [
	{
		name: 'content-width',
		value:
			toPixels( layout.contentSize ) === null
				? '768px'
				: `${ toPixels( layout.contentSize ) }px`,
		note: layout.contentSize
			? `from settings.layout.contentSize: ${ layout.contentSize }`
			: 'settings.layout.contentSize missing, using the 768px fallback',
	},
	{
		name: 'wide-width',
		value:
			toPixels( layout.wideSize ) === null
				? '1152px'
				: `${ toPixels( layout.wideSize ) }px`,
		note: layout.wideSize
			? `from settings.layout.wideSize: ${ layout.wideSize }`
			: 'settings.layout.wideSize missing, using the 1152px fallback',
	},
] ) }
${ renderSection( 'Breakpoints, compile-time only', [
	{
		name: 'breakpoint-md',
		value: '48em',
		note: 'medium layout breakpoint, 768px',
	},
	{
		name: 'breakpoint-lg',
		value: '64em',
		note: 'large layout breakpoint, 1024px',
	},
] ) }`;

mkdirSync( outputDir, { recursive: true } );
writeFileSync( outputPath, output, 'utf8' );

process.stdout.write(
	`Wrote ${ outputPath } (${ palette.length } palette, ${ fontSizes.length } font size, ${ spacingSizes.length } spacing size tokens)\n`
);
